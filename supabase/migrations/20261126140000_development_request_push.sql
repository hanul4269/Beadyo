-- =====================================================
-- 개발요청란 새 글 → 관리자 휴대폰 웹 푸시 알림
--
-- 흐름: development_requests INSERT
--       → 트리거가 pg_net으로 dev-request-push Edge Function 호출 (request_id만 전달)
--       → 함수가 push_subscriptions 에 등록된 기기로 웹 푸시 발송
--
-- 권한 설계
--   - 알림 등록은 private.push_owners 에 있는 계정만 가능 (이메일은 코드에 두지 않음)
--   - 등록 후에는 로그인 상태와 상관없이 계속 받음 (세션 만료·로그아웃·계정 전환 무관)
--   - 끄기는 기기의 "알림 끄기" 버튼으로만: 구독 주소(endpoint)를 아는 기기만 지울 수 있음
--   - 함수는 공개 호출이 가능하지만, 요청 1건당 1번만·생성 10분 이내 글만 발송
--     (development_request_push_log 의 기본키로 중복 차단)
--
-- 적용 후 준비(사용자가 직접, 값은 이 파일·채팅에 남기지 않음):
--   1) SQL Editor에서 알림 받을 계정을 한 번 등록:
--        insert into private.push_owners (user_id)
--        select id from auth.users where lower(email) = lower('<알림 받을 계정 이메일>')
--        on conflict do nothing;
--   2) Edge Function 비밀값 VAPID_PUBLIC_KEY / VAPID_PRIVATE_KEY / VAPID_SUBJECT
--   3) dev-request-push 함수를 verify_jwt = false 로 배포
--
-- 되돌리기: 파일 맨 아래 주석 참고.
-- =====================================================

create extension if not exists pg_net with schema extensions;
create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

-- 1. 알림 소유자
create table if not exists private.push_owners (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

revoke all on table private.push_owners from public, anon, authenticated;

create or replace function private.is_push_owner()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select auth.uid() is not null
     and exists (select 1 from private.push_owners where user_id = auth.uid());
$$;

revoke all on function private.is_push_owner() from public, anon, authenticated;

-- 화면에서 "알림 받기" 버튼을 보여줄지 판단하는 공개 RPC (true/false만 반환)
create or replace function public.can_register_push()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select private.is_push_owner();
$$;

revoke all on function public.can_register_push() from public, anon;
grant execute on function public.can_register_push() to authenticated;

-- 2. 구독 기기 목록 (클라이언트는 직접 접근 불가, RPC로만 등록/삭제)
create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  endpoint text not null unique
    check (endpoint ~ '^https://' and char_length(endpoint) <= 1000),
  p256dh text not null check (char_length(p256dh) between 20 and 200),
  auth_secret text not null check (char_length(auth_secret) between 8 and 100),
  user_agent text check (user_agent is null or char_length(user_agent) <= 300),
  created_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now()
);

alter table public.push_subscriptions enable row level security;
revoke all on table public.push_subscriptions from public, anon, authenticated;

comment on table public.push_subscriptions is
  '개발요청 알림을 받을 기기. 등록은 register_push_subscription RPC(소유자만), 삭제는 remove_push_subscription RPC(endpoint 보유 기기).';

create or replace function public.register_push_subscription(
  p_endpoint text,
  p_p256dh text,
  p_auth text,
  p_user_agent text default null
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not private.is_push_owner() then
    raise exception 'push registration is limited to the site owner'
      using errcode = '42501';
  end if;

  insert into public.push_subscriptions (user_id, endpoint, p256dh, auth_secret, user_agent)
  values (auth.uid(), p_endpoint, p_p256dh, p_auth, left(p_user_agent, 300))
  on conflict (endpoint) do update
    set user_id = excluded.user_id,
        p256dh = excluded.p256dh,
        auth_secret = excluded.auth_secret,
        user_agent = excluded.user_agent,
        last_seen_at = now();

  return true;
end;
$$;

revoke all on function public.register_push_subscription(text, text, text, text) from public, anon;
grant execute on function public.register_push_subscription(text, text, text, text) to authenticated;

-- 구독 주소는 그 기기만 알고 있으므로, 주소를 아는 쪽이면 로그인 여부와 무관하게 끌 수 있다.
create or replace function public.remove_push_subscription(p_endpoint text)
returns boolean
language sql
security definer
set search_path = ''
as $$
  with removed as (
    delete from public.push_subscriptions where endpoint = p_endpoint returning 1
  )
  select exists (select 1 from removed);
$$;

revoke all on function public.remove_push_subscription(text) from public;
grant execute on function public.remove_push_subscription(text) to anon, authenticated;

-- 3. 발송 기록 (요청 1건당 1번만 보내기 위한 잠금)
create table if not exists public.development_request_push_log (
  request_id bigint primary key references public.development_requests(id) on delete cascade,
  sent_at timestamptz not null default now()
);

alter table public.development_request_push_log enable row level security;
revoke all on table public.development_request_push_log from public, anon, authenticated;

-- 4. 새 요청 → Edge Function 호출 (실패해도 글 등록은 막지 않음)
create or replace function private.queue_development_request_push()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  base_url text;
begin
  -- 소유자가 직접 쓴 글은 알리지 않는다.
  if private.is_push_owner() then
    return new;
  end if;

  begin
    select decrypted_secret into base_url
      from vault.decrypted_secrets where name = 'beadyo_project_url';
  exception when others then
    base_url := null;
  end;
  base_url := coalesce(base_url, 'https://qlmcwobfldgmhwhptkfz.supabase.co');

  begin
    perform net.http_post(
      url := base_url || '/functions/v1/dev-request-push',
      body := jsonb_build_object('request_id', new.id),
      headers := jsonb_build_object('Content-Type', 'application/json'),
      timeout_milliseconds := 15000
    );
  exception when others then
    raise warning 'dev-request-push queue failed: %', sqlerrm;
  end;

  return new;
end;
$$;

revoke all on function private.queue_development_request_push() from public, anon, authenticated;

drop trigger if exists development_requests_push on public.development_requests;
create trigger development_requests_push
  after insert on public.development_requests
  for each row execute function private.queue_development_request_push();

